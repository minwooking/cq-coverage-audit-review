#!/usr/bin/env python3
"""Standalone validator for the AI-draft CSV of study mode AH.

Drafts are generated by a SEPARATE team, live OUTSIDE the repo, and are keyed
by cell_id in any order. This validator checks a draft file against the sealed
sheet and the rendered views WITHOUT importing the labeling server, so the
draft team can self-check before delivery:

    python validate_draft.py --draft draft_224.csv --sheet <sheet.csv> --views <dir>

Exit 0 with no ERROR lines = contract held; exit 1 prints every violation.
``validate_draft(draft_path, sheet_path, views_dir) -> list[str]`` is the
importable core (empty list = valid). The 7-field header contract defined
here is the single source of truth label_assist imports for --draft mode.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path
from typing import Final

DRAFT_HEADER: Final[tuple[str, ...]] = ("cell_id", "A_draft", "rater_L1_draft",
                                        "span_draft", "note_draft", "model", "generated_at")
A_DRAFT_VALUES: Final[frozenset[str]] = frozenset({"0", "1"})
L1_DRAFT_VALUES: Final[frozenset[str]] = frozenset({"0", "1", "2", "3"})


class DraftContractError(Exception):
    """Draft file unreadable or outside the 7-field header contract."""


def load_draft_records(draft_path: Path) -> list[dict[str, str]]:
    """Parse the whole draft into one dict per row, keyed by header name.

    Shared by validate_draft and label_assist so header drift between the two
    consumers is impossible."""
    if not draft_path.is_file():
        raise DraftContractError(f"초안 파일 없음: {draft_path}")
    with open(draft_path, newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh)
        header = next(reader, None)
        if header is None or [c.strip() for c in header] != list(DRAFT_HEADER):
            raise DraftContractError(
                f"초안 헤더가 7열 계약 {list(DRAFT_HEADER)}과 다릅니다: {header}")
        records: list[dict[str, str]] = []
        for lineno, rec in enumerate(reader, start=2):
            if len(rec) != len(DRAFT_HEADER):
                raise DraftContractError(
                    f"{draft_path.name} 줄 {lineno}: 열 {len(rec)}개 ≠ 7")
            records.append(dict(zip(DRAFT_HEADER, rec)))
    return records


def _sheet_variants(sheet_path: Path) -> dict[str, str]:
    """cell_id -> variant from the labeling sheet (columns located by name)."""
    if not sheet_path.is_file():
        raise DraftContractError(f"시트 파일 없음: {sheet_path}")
    with open(sheet_path, newline="", encoding="utf-8") as fh:
        reader = csv.reader(fh)
        header = [c.strip() for c in next(reader, [])]
        if "cell_id" not in header or "variant" not in header:
            raise DraftContractError(f"시트 헤더에 cell_id/variant 열이 없습니다: {header}")
        cid_i, var_i = header.index("cell_id"), header.index("variant")
        width = max(cid_i, var_i)
        return {r[cid_i]: r[var_i] for r in reader if len(r) > width}


def validate_draft(draft_path: Path, sheet_path: Path, views_dir: Path) -> list[str]:
    """Every contract violation as one human-readable error string; [] = valid.

    Cell-scoped rules: A_draft=1 requires a non-empty span_draft that is an
    exact substring of the cell's variant rendered view; A_draft=0 requires an
    empty span_draft and a non-empty note_draft."""
    errors: list[str] = []
    try:
        records = load_draft_records(draft_path)
        variants = _sheet_variants(sheet_path)
    except DraftContractError as exc:
        return [str(exc)]
    view_cache: dict[str, str | None] = {}

    def view_text(variant: str) -> str | None:
        if variant not in view_cache:
            path = views_dir / f"rendered_view_{variant}.txt"
            try:
                view_cache[variant] = path.read_text(encoding="utf-8")
            except OSError:
                view_cache[variant] = None
        return view_cache[variant]

    seen: set[str] = set()
    for rec in records:
        cid = rec["cell_id"]
        if cid in seen:
            errors.append(f"{cid}: cell_id 중복 등장")
            continue
        seen.add(cid)
        if cid not in variants:
            errors.append(f"시트에 없는 cell_id: {cid}")
        a = rec["A_draft"]
        if a not in A_DRAFT_VALUES:
            errors.append(f"{cid}: A_draft 허용값 0|1 (받은 값 {a!r})")
        if rec["rater_L1_draft"] not in L1_DRAFT_VALUES:
            errors.append(f"{cid}: rater_L1_draft 허용값 0|1|2|3 "
                          f"(받은 값 {rec['rater_L1_draft']!r})")
        for field in ("model", "generated_at"):
            if not rec[field].strip():
                errors.append(f"{cid}: {field} 비어 있음")
        span, note = rec["span_draft"], rec["note_draft"]
        if a == "1":
            if not span.strip():
                errors.append(f"{cid}: A_draft=1이면 span_draft가 비면 안 됩니다")
            elif cid in variants:
                text = view_text(variants[cid])
                if text is None:
                    errors.append(f"{cid}: 렌더된 뷰 파일을 읽을 수 없습니다 "
                                  f"(variant {variants[cid]})")
                elif span not in text:
                    errors.append(f"{cid}: span_draft가 variant {variants[cid]}의 "
                                  f"rendered view 원문이 아닙니다 (정확히 일치하는 부분문자열이어야 함)")
        elif a == "0":
            if span.strip():
                errors.append(f"{cid}: A_draft=0이면 span_draft가 비어 있어야 합니다")
            if not note.strip():
                errors.append(f"{cid}: A_draft=0이면 note_draft가 필요합니다")
    for cid in variants:
        if cid not in seen:
            errors.append(f"초안에 행이 없습니다 (시트 cell_id): {cid}")
    return errors


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="AI-draft CSV 계약 검증기 (exit 0=valid / 1=violations)")
    p.add_argument("--draft", required=True, type=Path, help="draft CSV (7열 계약, any order)")
    p.add_argument("--sheet", required=True, type=Path, help="라벨링 시트 CSV (cell_id·variant 열 보유)")
    p.add_argument("--views", required=True, type=Path, help="rendered_view_{V}.txt 디렉터리")
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    errors = validate_draft(Path(args.draft).expanduser(), Path(args.sheet).expanduser(),
                            Path(args.views).expanduser())
    for e in errors:
        print(f"ERROR: {e}")
    print(f"[validate_draft] {args.draft}: "
          + ("계약 통과 (0 오류)" if not errors else f"{len(errors)}개 오류 — 수정 후 재검증"))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
