#!/usr/bin/env python3
"""Addendum 36: LaTeX rows of the manuscript (Table A9 block, Supplementary Study 5 tables) from results.json.

AI-written helper; review before reuse. No model call, reads results.json only. Writes the .tex fragments to
paper_tables/ and cross-checks every delta and 95% interval against tables.tex (two-decimal intervals) and the
decisions against the stored verdicts. Exit status 1 on any mismatch.

The +-0.30 reading is the post hoc rule of addendum 34 amendment A3: an equivalent row (90% BCa inside +-0.50)
becomes unresolved where its 90% BCa interval is not inside (-0.30, +0.30); resolved and unresolved rows stay.

Usage: python3 -I paper_rows.py
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
D = json.load(open(os.path.join(HERE, 'results.json')))
OUT = os.path.join(HERE, 'paper_tables')
os.makedirs(OUT, exist_ok=True)

ORDER = ['glm', 'gptoss', 'q38', 'gw', 'q80']
NAME = {'glm': r'\texttt{GLM-4.7-Flash}', 'gptoss': r'\texttt{gpt-oss-20b}', 'q38': r'\texttt{Qwen3.8-Flash-Next}',
        'gw': r'\texttt{gpt-5.6-luna}', 'q80': r'\texttt{Qwen3-Next-80B-A3B}$^{\ddagger}$'}
PLAIN = {'glm': 'GLM-4.7-Flash', 'gptoss': 'gpt-oss-20b', 'q38': 'Qwen3.8-Flash-Next',
         'gw': 'gateway judge', 'q80': "Qwen3-Next-80B-A3B (extractor's model id)"}
SCOPE_NAME = {'brick_pool': 'Brick banks pooled', 'holdout': 'Holdout bank', 'paraphrases': 'Paraphrases',
              'v2_extras': 'Version-2 extras', 'expansion': 'Expansion bank', 'dcat': 'DCAT 3', 'ssn': 'SOSA/SSN',
              'prov': 'PROV', 'new_domains_pooled': 'Three domains pooled'}
ERRORS = []


def f3(x):
    return f'{x:+.3f}'


def dec50(c):
    v = c['verdict']
    if v.startswith('resolved'):
        return 'resolved'
    return {'equivalent': 'equivalent', 'unresolved': 'unresolved', 'underpowered': 'underpowered'}[v]


def dec30(c):
    v = dec50(c)
    if v == 'equivalent':
        lo, hi = c['ci90']
        if not (lo > -0.30 and hi < 0.30):
            return 'unresolved'
    return v


def cell(c):
    return (f"${f3(c['delta'])}$ $[{f3(c['ci95'][0])},{f3(c['ci95'][1])}]$", dec50(c), dec30(c))


def contrast(j, key):
    if j == 'mean':
        return D['panel_aggregate']['panel_mean_all']['contrasts'][key]
    return D['per_judge'][j]['contrasts'][key]


# ---- cross-check against tables.tex (generated by analyze.py, two-decimal intervals) --------------------------
T = open(os.path.join(HERE, 'tables.tex')).read()
pat = re.compile(r'^(?P<j>[^&%]+?) & (?P<rest>.*?) & (?P<n>\d+) & \$(?P<d>[+-]\d\.\d+)\$ \[\$(?P<lo>[+-]\d\.\d+)\$, \$(?P<hi>[+-]\d\.\d+)\$\] & (?P<dec>[a-zA-Z ]+) \\\\$', re.M)
SC_TEX = {'brick pool': 'brick_pool', 'new domains pooled': 'new_domains_pooled', 'dcat': 'dcat', 'ssn': 'ssn', 'prov': 'prov'}
inv = {v: k for k, v in PLAIN.items()}
nchk = 0
for m in pat.finditer(T):
    j = inv[m['j']]
    rest = m['rest']
    key = ('A->B|' + SC_TEX[rest]) if rest in SC_TEX else None
    if key is None:
        a = rest.split(' & ')
        key = a[0] + '|' + SC_TEX[a[1]]
    c = contrast(j, key)
    n = m['n']
    ok = (int(n) == c['n_clusters'] and abs(float(m['d']) - c['delta']) < 5.1e-4 and
          abs(float(m['lo']) - c['ci95'][0]) < 5.1e-3 and abs(float(m['hi']) - c['ci95'][1]) < 5.1e-3 and
          m['dec'].replace(' ', '_').replace('_gt_', '_gt_') .lower().split('_')[0] == c['verdict'].lower().split('_')[0])
    nchk += 1
    if not ok:
        ERRORS.append(('tables.tex mismatch', m.group(0), c['delta'], c['ci95'], c['verdict']))
print(f'cross-checked {nchk} rows of tables.tex against results.json')

# ---- Table A9 block: A->B pooled, five judges and the panel mean (the F rows are in the supplement for the page budget) ----------------------------------------------------------------------
def a9_block():
    L = []
    def head(title1, title2, n):
        L.append(r'\midrule')
        L.append(r'5 & \multicolumn{2}{l}{\emph{' + n + r'}} & \multicolumn{3}{c}{' + title1 + r'} & \multicolumn{3}{c}{' + title2 + r'} & \\')
        L.append(r'\cmidrule(lr){4-6}\cmidrule(lr){7-9}')
    head('$A\\!\\to\\!B$, Brick banks pooled ($n=58$)', '$A\\!\\to\\!B$, three domains pooled ($n=99$)', 'judge panel (addendum 36)')
    for j in ORDER + ['mean']:
        c1, c2 = contrast(j, 'A->B|brick_pool'), contrast(j, 'A->B|new_domains_pooled')
        a, b = cell(c1), cell(c2)
        nm = NAME[j] if j != 'mean' else 'Panel mean (descriptive)'
        L.append(f" & {nm} & & {a[0]} & {a[1]} & {a[2]} & {b[0]} & {b[1]} & {b[2]} & --- \\\\")
    return '\n'.join(L) + '\n'


# ---- Supplement: per-scope tables, one block per judge -----------------------------------------------------------
def long_rows(contrast_prefix, scopes):
    L = []
    for j in ORDER + ['mean']:
        nm = NAME[j] if j != 'mean' else 'Panel mean (descriptive)'
        for s in scopes:
            c = contrast(j, f'{contrast_prefix}|{s}')
            a = cell(c)
            L.append(f"{nm} & {SCOPE_NAME[s]} & ${c['n_clusters']}$ & {a[0]} & {a[1]} & {a[2]} \\\\")
        L.append(r'\midrule')
    L.pop()
    return '\n'.join(L) + '\n'


def decision_counts(key):
    s = D['panel_summary'][key]
    def t(g):
        x = s[g]
        return f"{x['resolved_second_gt_first']} / {x['resolved_first_gt_second']} / {x['equivalent']} / {x['unresolved']}"
    return t('independent'), t('same_family')


def summary_rows():
    L = []
    for pre in ['A->B', 'A->F', 'B->F']:
        scopes = [k.split('|')[1] for k in D['panel_summary'] if k.startswith(pre + '|')]
        order = [s for s in ['holdout', 'paraphrases', 'v2_extras', 'expansion', 'brick_pool', 'dcat', 'ssn', 'prov', 'new_domains_pooled'] if s in scopes]
        for s in order:
            ind, same = decision_counts(f'{pre}|{s}')
            L.append(f"${pre.replace('->', chr(92) + '!' + chr(92) + 'to' + chr(92) + '!')}$ & {SCOPE_NAME[s]} & {ind} & {same} \\\\")
        L.append(r'\midrule')
    L.pop()
    return '\n'.join(L).replace('$A\\!\\to\\!B$', '$A\\!\\to\\!B$') + '\n'


def qwk_rows(which):
    q = D['agreement_qwk'][which]
    L = []
    for pair, v in q.items():
        a, b = pair.split('~')
        L.append(f"{PLAIN[a].replace('gateway judge', 'gpt-5.6-luna').split(' (')[0]} -- {PLAIN[b].replace('gateway judge', 'gpt-5.6-luna').split(' (')[0]} & ${v['n_cells']}$ & ${v['qwk']:.3f}$ & ${v['exact_agreement']:.3f}$ \\\\")
    return '\n'.join(L) + '\n'


def write(name, s):
    open(os.path.join(OUT, name), 'w').write(s)


assert (contrast('glm','A->B|brick_pool')['n_clusters'], contrast('glm','A->B|new_domains_pooled')['n_clusters'], contrast('glm','A->F|new_domains_pooled')['n_clusters'], contrast('glm','B->F|new_domains_pooled')['n_clusters']) == (58, 99, 99, 103)
write('a9_rows.tex', a9_block())
write('supp_ab_rows.tex', long_rows('A->B', ['holdout', 'paraphrases', 'v2_extras', 'expansion', 'brick_pool', 'dcat', 'ssn', 'prov', 'new_domains_pooled']))
write('supp_af_rows.tex', long_rows('A->F', ['dcat', 'ssn', 'prov', 'new_domains_pooled']))
write('supp_bf_rows.tex', long_rows('B->F', ['dcat', 'ssn', 'prov', 'new_domains_pooled']))
write('supp_summary_rows.tex', summary_rows())
write('supp_qwk_ab_rows.tex', qwk_rows('A_B_cells'))
write('supp_qwk_f_rows.tex', qwk_rows('F_cells'))
if ERRORS:
    for e in ERRORS:
        print('MISMATCH', e)
    sys.exit(1)
print('ok')
