"""Render REPORT_auto.md and tables.tex from results.json (no recomputation)."""
import json
from pathlib import Path
here = Path(__file__).parent
r = json.loads((here / "results.json").read_text())

def sv(x):
    if x.get("shacl_conforms") is None: return "n/a"
    return "yes" if x["shacl_conforms"] else f"no ({x['shacl_violations']})"
def ov(x):
    return {True: "yes", False: "no", None: "n/a"}[x.get("owl_consistent")]
def dr(x):
    s = x["domain_range_share"]
    return f"{x['props_with_domain_and_range']}/{x['properties']} ({100*s:.0f}\\%)" if s is not None else "--"

short = {"second domain (counts only)": "Second domain"}
rows = []
for n, d in r["domains"].items():
    dd = ("%d dropped; %d pred., %d ent. merged" % (d["d_triples_dropped"], d["d_predicates_merged"], d["d_entities_merged"])
          if "d_triples_dropped" in d else "not logged")
    for v, x in d["variants"].items():
        rows.append((short.get(n, n), v, x, dd))

tex = [r"% auto-generated by make_report.py from results.json (study 7)",
       r"\begin{tabular}{@{}llrrrrll@{}}", r"\toprule",
       r"Domain & Var. & Triples & Props.\ with dom.+range & PROV (derived/all) & SHACL (viol.) & OWL & D dedup \\", r"\midrule"]
last = None
for n, v, x, dd in rows:
    if last and n != last: tex.append(r"\midrule")
    dom = n if n != last else ""
    last = n
    ddc = dd if v == "D" else ""
    tex.append(f"{dom} & {v} & {x['triples']:,} & {dr(x)} & {x['prov_wasDerivedFrom']}/{x['prov_links']} & {sv(x)} & {ov(x)} & {ddc} \\\\".replace("'", "$'$"))
tex += [r"\bottomrule", r"\end{tabular}"]
(here / "tables.tex").write_text("\n".join(tex) + "\n")

md = ["# Study 7 - structural outputs per stage (auto-generated)", "",
      "Source: released graph files, counted with rdflib; SHACL (project `stage5_shacl` shapes + pyshacl, rdfs inference) and OWL (`owlrl` closure, no `owl:Nothing`) via `chunktograph.metrics.validity`. No model calls. Second-domain graphs: numeric counts only.", "",
      "| Domain | V | triples | classes | props | dom+range (n/share) | skos:broader | entity types | PROV derived/all | SHACL | OWL |", "|---|---|---|---|---|---|---|---|---|---|---|"]
for n, v, x, dd in rows:
    md.append(f"| {short.get(n,n)} | {v} | {x['triples']} | {x['classes']} | {x['properties']} | {dr(x).replace(chr(92),'')} | {x['skos_broader']} | {x['entity_type_statements']} | {x['prov_wasDerivedFrom']}/{x['prov_links']} | {sv(x)} | {ov(x)} |")
md += ["", "## Dedup at D and standards alignment (from logs)", "", "| Domain | triples in->out (dropped) | predicates merged | entities merged | predicates aligned to standard (E) |", "|---|---|---|---|---|"]
for n, d in r["domains"].items():
    if "d_triples_dropped" in d:
        md.append(f"| {n} | {d['d_triples_in']}->{d['d_triples_out']} ({d['d_triples_dropped']}) | {d['d_predicates_merged']} | {d['d_entities_merged']} | {d['aligned_predicates']}/{d['alignment_total']} |")
    else:
        md.append(f"| {n} | not logged | not logged | not logged | not recorded |")
md += ["", "## Provenance of inputs (path, sha256)", ""]
for n, d in r["domains"].items():
    for v, x in d["variants"].items():
        if "file" in x: md.append(f"- {n} {v}: `{x['file']}` `{x['sha256'][:16]}`")
        else: md.append(f"- {n} {v}: MISSING `{x['missing']}`")
for n, d in r["domains"].items():
    for k in ("dedup_file", "alignment_file"):
        if k in d: md.append(f"- {n} {k}: `{d[k]}`")
md += ["", "Released F shapes (`shapes_F.ttl`) conformance: " + ", ".join(f"{n}={d['variants']['F'].get('released_shapes_conform')}" for n, d in r["domains"].items() if "F" in d["variants"])]
(here / "REPORT_auto.md").write_text("\n".join(md) + "\n")
